// Builds the full A/B matrix from every bench/results/round*.json + bench/pricing.json → bench/MATRIX.md
// Arms that ran in several rounds are pooled (more samples, less noise). Round 0 used an older prompt and is skipped.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { ARMS, DEFAULT_ARM } from '../src/arms.mjs';

const dir = new URL('./results/', import.meta.url);
const price = JSON.parse(readFileSync(new URL('./pricing.json', import.meta.url)));
const files = readdirSync(dir).filter(f => /^round[1-9].*\.json$/.test(f)).sort();

const byArm = {};
for (const f of files) for (const a of JSON.parse(readFileSync(new URL(f, dir)))) {
  const id = a.summary.arm;
  (byArm[id] ||= { rounds: new Set(), rs: [] }).rounds.add(f.match(/round(\d)/)[1]);
  byArm[id].rs.push(...a.results.filter(r => 'score' in r));
}

const pct = (a, p) => { const s = [...a].sort((x, y) => x - y); return s[Math.min(s.length - 1, Math.floor(p * s.length))]; };
const mean = a => a.reduce((x, y) => x + y, 0) / a.length;

const rows = Object.entries(byArm).filter(([id]) => ARMS[id]).map(([id, { rounds, rs }]) => {
  const arm = ARMS[id];
  const p = price[arm.model]?.[arm.service_tier === 'priority' ? 'fast' : 'standard'];
  const inTok = mean(rs.map(r => r.usage?.prompt_tokens || 0)), outTok = mean(rs.map(r => r.usage?.completion_tokens || 0));
  const cost = p ? (inTok * p[0] + outTok * p[1]) : null; // $ per 1M calls = tokens × $/1M tokens
  const cats = {};
  for (const r of rs) (cats[r.cat] ||= []).push(r.score);
  return {
    id, arm, rounds: [...rounds].join(','), n: rs.length,
    score: mean(rs.map(r => r.score)), top: 100 * rs.filter(r => r.score >= 9).length / rs.length,
    f50: pct(rs.map(r => r.first_ms ?? r.total_ms), 0.5), f90: pct(rs.map(r => r.first_ms ?? r.total_ms), 0.9),
    t50: pct(rs.map(r => r.total_ms), 0.5), t90: pct(rs.map(r => r.total_ms), 0.9),
    inTok, outTok, cost, cats: Object.fromEntries(Object.entries(cats).map(([c, v]) => [c, mean(v)])),
  };
}).sort((a, b) => b.score - a.score);

const base = rows.find(r => r.id === DEFAULT_ARM);
const f1 = x => x.toFixed(1), f2 = x => x.toFixed(2);
const tier = a => a.service_tier === 'priority' ? 'fast' : 'standard';
let md = `# Job-title suggest — full A/B matrix\n\n` +
  `Generated by \`node bench/matrix.mjs\` from ${files.join(', ')}. Pricing: ${price._source}\n\n` +
  `Score = gpt-5.5 judge, 0–10, mean over all runs (54 queries × reps × rounds). Latency in ms from the benchmark host. ` +
  `Cost = measured avg tokens × list price, **per 1M uncached suggestion calls** (cache hits cost $0). Current default: \`${DEFAULT_ARM}\`.\n\n` +
  `## Quality × speed × cost\n\n` +
  `| arm | model | reasoning | prompt | tier | runs | score | ≥9 % | 1st p50 | 1st p90 | all p50 | all p90 | in tok | out tok | $ / 1M calls | cost vs default |\n` +
  `|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
for (const r of rows) md += `| ${r.id === DEFAULT_ARM ? '**' + r.id + '** (default)' : r.id} | ${r.arm.model} | ${r.arm.reasoning_effort || '–'} | ${r.arm.prompt} | ${tier(r.arm)} | ${r.n} | ${f2(r.score)} | ${Math.round(r.top)} | ${r.f50} | ${r.f90} | ${r.t50} | ${r.t90} | ${Math.round(r.inTok)} | ${Math.round(r.outTok)} | ${r.cost == null ? 'n/a' : '$' + r.cost.toFixed(0)} | ${r.cost == null || !base?.cost ? 'n/a' : (r.cost / base.cost).toFixed(2) + '×'} |\n`;

const cats = [...new Set(rows.flatMap(r => Object.keys(r.cats)))];
md += `\n## Score by query category\n\n| arm | ${cats.join(' | ')} |\n|---|${cats.map(() => '---').join('|')}|\n`;
for (const r of rows) md += `| ${r.id} | ${cats.map(c => r.cats[c] == null ? '' : f1(r.cats[c])).join(' | ')} |\n`;
writeFileSync(new URL('./MATRIX.md', import.meta.url), md);
console.log(md);
